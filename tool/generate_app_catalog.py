"""Validate ARB catalogs and generate bundled Flutter message maps.

Run from the repository root: python3 tool/generate_app_catalog.py --check
No runtime asset loading, network access or third-party generator is required.
"""
import argparse
import json
import pathlib
import re

ROOT = pathlib.Path(__file__).resolve().parents[1]
L10N = ROOT / 'lib/l10n'

def read(name):
    data = json.loads((L10N / name).read_text())
    return {key: value for key, value in data.items() if not key.startswith('@')}

def generate():
    english = read('app_en.arb')
    roman = read('app_ur_Latn.arb')
    spoken = read('speech_ur.arb')
    if english.keys() != roman.keys():
        raise ValueError('English and Roman Urdu catalog keys differ')
    for key, translation in roman.items():
        parameters = set(re.findall(r'\{(p\d+)\}', english[key]))
        if parameters != set(re.findall(r'\{(p\d+)\}', translation)):
            raise ValueError(f'Placeholder mismatch: {key}')
    for key, translation in spoken.items():
        if key not in english:
            raise ValueError(f'Unknown speech key: {key}')
        if not set(re.findall(r'\{(p\d+)\}', translation)) <= set(re.findall(r'\{(p\d+)\}', english[key])):
            raise ValueError(f'Unexpected speech parameter: {key}')
    def dart_string(value):
        return json.dumps(value, ensure_ascii=False).replace('$', '\\$')
    result = '// Generated by tool/generate_app_catalog.py. Edit the ARB files.\n'
    for name, catalog in [('englishMessages', english), ('romanUrduMessages', roman), ('urduSpeechMessages', spoken)]:
        result += f'const {name} = <String, String>{{\n'
        result += ''.join(f'  {dart_string(k)}: {dart_string(v)},\n' for k, v in catalog.items())
        result += '};\n\n'
    return result, len(english), len(spoken)

if __name__ == '__main__':
    parser = argparse.ArgumentParser()
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    output, written_count, speech_count = generate()
    path = L10N / 'app_catalog.g.dart'
    if args.check:
        if not path.exists() or path.read_text() != output:
            raise SystemExit('Generated catalog is stale; run python3 tool/generate_app_catalog.py')
    else:
        path.write_text(output)
    print(f'Catalog validated: {written_count} written messages, {speech_count} Urdu speech messages')
